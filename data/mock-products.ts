function variants(productId: string, price: number, stock: number, sizes = ["5", "6", "7", "8", "9"]) {
  return sizes.map((size, index) => ({
    id: `${productId}-v-${index + 1}`,
    productId,
    title: size ? `Size ${size}` : "Tiêu chuẩn",
    sku: `TB-${productId.toUpperCase()}-${size || "STD"}`,
    size,
    color: "Bạc",
    price: price + index * 10000,
    compareAtPrice: index % 2 === 0 ? price + 90000 : undefined,
    costPrice: Math.round(price * 0.46),
    active: true,
    inventory: {
      variantId: `${productId}-v-${index + 1}`,
      quantityAvailable: Math.max(stock - index * 2, 0),
      quantityReserved: index,
      quantitySold: 18 + index * 3,
      lowStockThreshold: 4,
    },
  }));
}

